"""
build_standalone.py
 
Bundles a runner script with the local modules it imports (e.g. a comparison_models
file and load_data.py) into a single self-contained .py file, for HPC systems where
imports from other files are awkward. Module code is copied verbatim, so the
standalone file runs exactly the same code as the repository version.
 
Usage (from the repo root):
    # Simulation runner: model only
    python hpc/build_standalone.py simulation/run_scdeepcluster.py \
        comparison_models/scdeepcluster.py \
        -o hpc/scdeepcluster_sim_standalone.py
 
    # Real-data runner: model + data loaders
    python hpc/build_standalone.py run_scdeepcluster.py \
        comparison_models/scdeepcluster.py load_data.py \
        -o hpc/scdeepcluster_real_standalone.py
 
Modules are inlined in the order given, then the runner.
"""
 
import argparse
import ast
from pathlib import Path
 
 
def strip_local_imports(src, module_names):
    """Remove sys.path.insert lines and imports of the inlined modules
    (handles single-line and parenthesised multi-line imports)."""
    out, skipping = [], False
    for line in src.splitlines():
        stripped = line.strip()
        if skipping:
            if ")" in stripped:
                skipping = False
            continue
        if stripped.startswith("sys.path.insert("):
            continue
        is_local = any(
            stripped.startswith(f"from {m} import") or stripped.startswith(f"import {m}")
            for m in module_names
        )
        if is_local:
            if "(" in stripped and ")" not in stripped:
                skipping = True
            continue
        out.append(line)
    return "\n".join(out)
 
 
def split_future(src):
    """Separate 'from __future__' lines (must go at the very top of the file)."""
    future, rest = [], []
    for line in src.splitlines():
        (future if line.strip().startswith("from __future__") else rest).append(line)
    return future, "\n".join(rest)
 
 
def top_level_names(src):
    names = set()
    for node in ast.parse(src).body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    names.add(t.id)
    return names
 
 
def main():
    p = argparse.ArgumentParser()
    p.add_argument("runner")
    p.add_argument("modules", nargs="+", help="Local module files to inline, in order")
    p.add_argument("-o", "--output", required=True)
    a = p.parse_args()
 
    module_paths = [Path(m) for m in a.modules]
    # Names the runner may import them by, e.g. 'comparison_models.scdeepcluster', 'load_data'
    import_names = set()
    for mp in module_paths:
        import_names.add(mp.stem)
        import_names.add(".".join(mp.with_suffix("").parts[-2:]))
    import_names.add("comparison_models")
 
    sections, futures, seen = [], [], {}
    for mp in module_paths:
        src = strip_local_imports(mp.read_text(), import_names)
        fut, src = split_future(src)
        futures += [f for f in fut if f not in futures]
        for name in top_level_names(src):
            if name in seen:
                print(f"WARNING: '{name}' is defined in both {seen[name]} and {mp}; "
                      f"the later definition ({mp}) wins.")
            seen[name] = str(mp)
        sections.append(f"# {'=' * 60}\n# Inlined from {mp}\n# {'=' * 60}\n\n{src.strip()}\n")
 
    runner_src = strip_local_imports(Path(a.runner).read_text(), import_names)
    fut, runner_src = split_future(runner_src)
    futures += [f for f in fut if f not in futures]
    for name in top_level_names(runner_src):
        if name in seen and name != "main":
            print(f"WARNING: '{name}' is defined in both {seen[name]} and the runner; "
                  f"the runner's definition wins.")
 
    header = (f"# AUTO-GENERATED by build_standalone.py from {a.runner} + "
              f"{', '.join(a.modules)}.\n# Edit those files, not this one.\n")
    out = (header + "\n".join(futures) + "\n\n" + "\n\n".join(sections)
           + f"\n\n# {'=' * 60}\n# Runner: {a.runner}\n# {'=' * 60}\n\n"
           + runner_src.strip() + "\n")
 
    ast.parse(out)  # fail loudly if the result isn't valid Python
    Path(a.output).write_text(out)
    print(f"Wrote {a.output}")
 
 
if __name__ == "__main__":
    main()