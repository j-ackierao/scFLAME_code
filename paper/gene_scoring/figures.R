# ── Run with ClusterProfiler instead ──────────────────────────────────────────

run_cluster_gsea_cp <- function(k, data) {
  ranks <- data |>
    dplyr::filter(cluster_k == as.numeric(k)) |>
    dplyr::arrange(dplyr::desc(score)) |>
    (\(x) stats::setNames(x$score, x$gene))()

  term2gene <- m_df |>
    dplyr::select(gs_name, gene_symbol)

  clusterProfiler::GSEA(
    geneList      = ranks,
    TERM2GENE     = term2gene,
    minGSSize     = 10,
    maxGSSize     = 500,
    pvalueCutoff  = 1,
    eps           = 0,
    seed          = TRUE,
    pAdjustMethod = "BH"
  )
}

