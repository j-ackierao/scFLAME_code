    )

  # ── Panel 2: Barcode ───────────────────────────────────────────────────────
  n <- length(top_ids)
  barcode_data <- do.call(rbind, lapply(seq_along(top_ids), function(i) {
    d <- enrichplot:::gsInfo(res, top_ids[i])
    d |>
      filter(position == 1) |>
      mutate(
        pathway = top_ids[i],
        label   = label_map[top_ids[i]],
        ymin    = (i - 1) / n,
        ymax    = i / n - 0.05,
        color   = colors[i]
      )
  }))

  p2 <- ggplot(barcode_data, aes(
    x = x, xend = x,
    y = ymin, yend = ymax,
    colour = label
  )) +
    geom_segment(linewidth = 0.15) +
    scale_colour_manual(values = setNames(colors, label_map[top_ids])) +
    scale_x_continuous(expand = c(0.01, 0)) +
    scale_y_continuous(expand = c(0, 0)) +
    labs(x = "Gene Rank", y = NULL) +
