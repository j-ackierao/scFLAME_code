# ── Run FGSEA for Target Clusters ──────────────────────────────────────────
run_cluster_fgsea <- function(k, data, pathways) {
  cluster_data <- data |>
    filter(cluster_k == as.numeric(k)) |>
    arrange(desc(score))

  ranks <- setNames(cluster_data$score, cluster_data$gene)

  fgsea_res <- fgseaMultilevel(
    pathways = pathways, stats = ranks,
    minSize = 10, maxSize = 500, eps = 0
  )

  if (is.null(fgsea_res) || nrow(fgsea_res) == 0) {
    return(NULL)
  }
  fgsea_res |>
    as_tibble() |>
    mutate(cluster_k = as.character(k))
}

all_gsea_results <- map_dfr(c(0:7), ~ run_cluster_fgsea(.x, df_ranked, pathways_list))
