# Run Pathway Enrichment
run_enrichment <- function(k, data) {
  # Get top 50 genes for this cluster
  genes <- data |>
    filter(cluster_k == k, score > 0) |>
    slice_max(score, n = 50) |>
    pull(gene)

  # Run Gene Ontology (Biological Process) enrichment
  res <- enrichGO(
    gene          = genes,
    OrgDb         = org.Hs.eg.db,
    keyType       = "SYMBOL",
    ont           = "BP", # Biological Process
    pAdjustMethod = "BH", # Benjamini-Hochberg FDR
    pvalueCutoff  = 0.05,
    qvalueCutoff  = 0.2
  )

  if (is.null(res) || nrow(res@result) == 0) {
    return(NULL)
  }

  # Add cluster ID to results
  res@result |> mutate(cluster_k = as.character(k))
}

