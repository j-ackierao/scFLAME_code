# Example function to calculate Jaccard index between two character vectors
calculate_jaccard <- function(list_a, list_b) {
  intersection <- length(intersect(list_a, list_b))
  union <- length(union(list_a, list_b))
  if (union == 0) {
    return(0)
  }
  intersection / union
}

