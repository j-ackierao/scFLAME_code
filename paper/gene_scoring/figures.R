plot_gsea_clean <- function(res, top_ids, title,
                            colors = c("#9970AB", "#D95F02", "#1B9E77")) {
  colors <- colors[seq_along(top_ids)]

  # ── Extract enrichment curve data ─────────────────────────────────────────
  gsdata <- do.call(rbind, lapply(seq_along(top_ids), function(i) {
    enrichplot:::gsInfo(res, top_ids[i]) |>
      mutate(pathway = top_ids[i], color = colors[i])
  }))

  # Shorten labels for legend
  label_map <- setNames(
    str_trunc(str_replace(top_ids, "GSE[0-9]+_", ""), 45, ellipsis = "…"),
    top_ids
  )
  gsdata$label <- label_map[gsdata$pathway]

  # ── Panel 1: Running ES curve ──────────────────────────────────────────────
  p1 <- ggplot(gsdata, aes(x = x, y = runningScore, colour = label)) +
    geom_hline(yintercept = 0, linewidth = 0.25, colour = "grey50", linetype = "dashed") +
    geom_line(linewidth = 0.4) +
    scale_colour_manual(values = setNames(colors, label_map[top_ids])) +
    scale_x_continuous(expand = c(0.01, 0)) +
    labs(x = NULL, y = "Running Enrichment Score", title = title, colour = NULL) +
    theme_classic(base_size = 5.8) +
    theme(
      plot.title = element_text(size = 5.8, face = "bold"),
      axis.text.x = element_blank(),
      axis.ticks.x = element_blank(),
      axis.line.x = element_blank(),
      axis.title.y = element_text(size = 5.8),
      axis.text.y = element_text(size = 5.8),
      legend.position = c(1.03, 1.08),
      legend.justification = c(1, 1),
      legend.text = element_text(size = 5),
      legend.key.height = unit(1.5, "mm"),
      legend.key.width = unit(3, "mm"),
      legend.background = element_blank(),
      plot.margin = margin(2, 2, 0, 2)
    )

  # ── Panel 2: Barcode ───────────────────────────────────────────────────────
  # Each pathway gets its own horizontal strip
  n <- length(top_ids)
  barcode_data <- do.call(rbind, lapply(seq_along(top_ids), function(i) {
    d <- enrichplot:::gsInfo(res, top_ids[i])
    d |>
      filter(position == 1) |>
      mutate(
        pathway = top_ids[i],
        label   = label_map[top_ids[i]],
        ymin    = (i - 1) / n,
        ymax    = i / n - 0.05,
        color   = colors[i]
      )
  }))

  p2 <- ggplot(barcode_data, aes(
    x = x, xend = x,
    y = ymin, yend = ymax,
    colour = label
  )) +
    geom_segment(linewidth = 0.15) +
    scale_colour_manual(values = setNames(colors, label_map[top_ids])) +
    scale_x_continuous(expand = c(0.01, 0)) +
    scale_y_continuous(expand = c(0, 0)) +
    labs(x = "Gene Rank", y = NULL) +
    theme_classic(base_size = 5.8) +
    theme(
      axis.text.y       = element_blank(),
      axis.ticks.y      = element_blank(),
      axis.line.y       = element_blank(),
      axis.text.x       = element_text(size = 5.5),
      axis.title.x      = element_text(size = 5.5),
      legend.position   = "none",
      plot.margin       = margin(0, 2, 2, 2)
    )

  # ── Combine with patchwork ─────────────────────────────────────────────────
  p1 / p2 + plot_layout(heights = c(4, 1))
}

